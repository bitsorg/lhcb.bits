"""Write defaults-lhcb.sh's version overrides from an LHCb LCG flavour's lcginfo.json.

Each lcg.bits recipe at another version gets one, between the markers; entries
written by hand outside them win. See README, "LHCb versions"."""
import argparse
import json
import os
import re
import sys
import urllib.error
import urllib.request

import yaml

BEGIN = "  # --- generated by tools/lcg-deltas.py: do not edit by hand ---"
END = "  # --- end of generated overrides ---"
# Build labels LCG adds that lcg.bits leaves out (blas 0.3.29.openblas).
LABEL = re.compile(r"(.*\d)\.openblas$")
# A variant (3.3.1.lhcb1, 317.lhcb): a patched build, unless lcg.bits has its patch.
VARIANT = re.compile(r"\.(?!post|dev|rc)[a-z]+\d*$")


def key(name):
    """Match LCG and lcg.bits names: case, - and _, ++ (Garfield++ is GarfieldCPP)."""
    return re.sub(r"[^a-z0-9]", "", name.lower().replace("++", "cpp"))


def core(v):
    """A version from its first digit, with dots: v01-36, 01.36 and CLHEP_01_36 give 01.36."""
    v = str(v)
    m = re.search(r"\d.*", v)
    return re.sub(r"[-_]", ".", m.group(0)) if m else v


def same(a, b):
    """The same version, leading zeros aside (02.02.01 is 2.2.1)."""
    n = lambda v: [x.lstrip("0") or "0" if x.isdigit() else x for x in core(v).split(".")]
    return n(a) == n(b)


# How a recipe writes a version (core c): as is, v-prefixed, - or _ separated.
FORMS = [lambda c: c, lambda c: "v" + c,
         lambda c: c.replace(".", "-"), lambda c: "v" + c.replace(".", "-"),
         lambda c: c.replace(".", "_"), lambda c: "v" + c.replace(".", "_")]


def follow(literal, old, new):
    """*literal* (a tag, a URL) with version *old* replaced by *new*, each time in
    the form it has there, or None when *old* is not in it."""
    out, hit = literal, False
    for f in sorted(FORMS, key=lambda f: len(f(core(old))), reverse=True):
        rx = re.compile(r"(?<![0-9])" + re.escape(f(core(old))) + r"(?![0-9]|\.[0-9])")
        if rx.search(out):
            out, hit = rx.sub(lambda m: f(core(new)), out), True
    return out if hit else None


def recipes(path, report):
    """{key: header} of every recipe in an lcg.bits checkout."""
    out = {}
    for fn in sorted(os.listdir(path)):
        if not fn.endswith(".sh") or fn.startswith("defaults-"):
            continue
        with open(os.path.join(path, fn)) as fh:
            head = fh.read().split("\n---", 1)[0]
        try:
            h = yaml.safe_load(head) or {}
        except yaml.YAMLError:
            report["unreadable recipe"].append(fn)
            continue
        if not (isinstance(h, dict) and h.get("package") and h.get("version") is not None):
            continue
        h["_gates"] = re.findall(r"version=([^\s\"'&]+)", head)   # patches per version
        h["_patches"] = [str(p).split(":")[0] for p in h.get("patches") or [] if "version=" not in str(p)]
        k = key(h["package"])
        if k in out:
            report["ambiguous name"].append("%s and %s" % (out[k]["package"], h["package"]))
        out[k] = h
    return out


def split_defaults(text, path):
    """(text before the generated block, after it) and the overrides written by hand."""
    if BEGIN in text:
        pre, rest = text.split(BEGIN, 1)
        if END not in rest:
            sys.exit("%s: the generated block has no end marker:\n%s" % (path, END))
        post = rest.split(END, 1)[1]
    else:
        pre, post = text, ""
    head = (pre + post).split("\n---", 1)[0]
    hand = (yaml.safe_load(head) or {}).get("overrides") or {}
    return pre, post, hand


def url_ok(url, tries=2):
    for _ in range(tries):
        try:
            req = urllib.request.Request(url, method="HEAD")
            with urllib.request.urlopen(req, timeout=30) as r:
                return r.status < 400
        except urllib.error.HTTPError as e:
            if e.code < 500:
                return False
        except (urllib.error.URLError, OSError):
            pass
    return False


def recipe_version(h):
    """The version a recipe builds: its tag when the version is the tag's."""
    v = str(h["version"])
    return str(h.get("tag")) if "%(tag_basename)s" in v and h.get("tag") else v


def lcg_version(lv, rv):
    """LCG's version without a build label lcg.bits does not use."""
    m = LABEL.match(lv)
    return m.group(1) if m and not LABEL.match(rv) else lv


def keep_reason(h, lv):
    """Why recipe *h* cannot build LCG version *lv* (it stays at its own), or None."""
    rv = recipe_version(h)
    nv = follow(rv, rv, lv)
    if h["_gates"] and nv not in h["_gates"]:
        return "its patches are for %s" % ", ".join(h["_gates"])
    if VARIANT.search(lv) and not VARIANT.search(rv):
        return "a patched build lcg.bits has no patch for"
    for p in h["_patches"]:
        if follow(p, rv, rv) is not None:
            return "patch %s is for %s" % (p, rv)
    return None


def override(h, lv, check):
    """{field: value} making recipe *h* build LCG version *lv*, and problems."""
    rv = recipe_version(h)
    nv = follow(rv, rv, lv)
    ov, problems = {}, []
    if "%(" not in str(h["version"]):
        ov["version"] = nv
    tag = h.get("tag")
    if tag is not None and "%(" not in str(tag):
        t = follow(str(tag), rv, lv)
        if t is None:
            problems.append("tag %s does not show version %s" % (tag, rv))
        else:
            ov["tag"] = t
    sources = [str(x) for x in h.get("sources") or []]
    expand = lambda x, v=nv: x.replace("%(version)s", v).replace("%(name)s", h["package"])
    srcs = []
    for s in sources:
        if "%(version)s" in s:
            mine, lcgs = s, s.replace("%(version)s", lv)
            # The LCG mirror names its tarballs with LCG's versions (DD4hep-01.37).
            u, alt = (lcgs, mine) if nv != lv and "lcgpackages.web.cern.ch" in s else (mine, lcgs)
        else:
            u, alt = follow(s, rv, lv), None
            if u is None:
                if follow(s, lv, lv) is None:   # nor already the new one
                    problems.append("source %s does not show version %s" % (s, rv))
                u = s
        if check and not url_ok(expand(u)):
            if alt and expand(alt) != expand(u) and url_ok(expand(alt)):
                u = alt
            elif url_ok(expand(s, str(h["version"]))):   # else not reachable from here
                problems.append("no source at %s" % expand(u))
        srcs.append(u)
    if srcs != sources:
        ov["sources"] = srcs
    return ov, problems


def block(ovs, src):
    lines = [BEGIN, "  # %s" % src]
    for name in sorted(ovs, key=str.lower):
        lines.append("  %s:" % name)
        for k in ("version", "tag"):
            if k in ovs[name]:
                lines.append("    %s: %s" % (k, json.dumps(ovs[name][k])))
        if "sources" in ovs[name]:
            lines.append("    sources:")
            lines += ["      - %s" % json.dumps(s) for s in ovs[name]["sources"]]
    return "\n".join(lines + [END])


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--lcginfo", required=True, help="lcg-toolchains/LCG_<ver>/lcginfo.json")
    p.add_argument("--flavour", required=True, help="e.g. LHCB_11")
    p.add_argument("--platform", required=True, help="e.g. x86_64-el9-gcc15-opt")
    p.add_argument("--recipes", required=True, help="an lcg.bits checkout")
    p.add_argument("--defaults", default=os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "defaults-lhcb.sh"))
    p.add_argument("--closure", help="`bits status --json lcg-externals` output: "
                   "only its packages get an override")
    p.add_argument("--check-urls", action="store_true",
                   help="check the new source tarballs exist")
    p.add_argument("--write", action="store_true", help="update --defaults in place")
    a = p.parse_args(argv)

    report = {"unreadable recipe": [], "ambiguous name": [], "no lcg.bits recipe": [],
              "not in the closure": [], "written by hand, differs": [],
              "kept at the lcg.bits version": [], "needs a hand override": []}
    with open(a.lcginfo) as fh:
        lcg = json.load(fh)[a.flavour][a.platform]["packages"]
    rec = recipes(a.recipes, report)
    with open(a.defaults) as fh:
        text = fh.read()
    pre, post, hand = split_defaults(text, a.defaults)
    hand = {key(n): (n, v) for n, v in hand.items()}
    closure = None
    if a.closure:
        with open(a.closure) as fh:
            closure = {key(x["package"]) for x in json.load(fh)["packages"]}

    ovs = {}
    for name, info in sorted(lcg.items(), key=lambda kv: kv[0].lower()):
        lv, k = str(info["version"]), key(name)
        h = rec.get(k)
        if h is None:
            report["no lcg.bits recipe"].append("%s %s" % (name, lv))
            continue
        if k in hand:
            hv = (hand[k][1] or {}).get("version")
            if hv is not None and not same(hv, lv):
                report["written by hand, differs"].append("%s %s (LCG %s)" % (hand[k][0], hv, lv))
            continue
        lv = lcg_version(lv, recipe_version(h))
        if same(recipe_version(h), lv):
            continue
        if closure is not None and k not in closure:
            report["not in the closure"].append("%s %s (lcg.bits %s)" % (name, lv, recipe_version(h)))
            continue
        why = keep_reason(h, lv)
        if why:
            report["kept at the lcg.bits version"].append(
                "%s %s, LCG %s: %s" % (h["package"], recipe_version(h), lv, why))
            continue
        ov, problems = override(h, lv, a.check_urls)
        ovs[h["package"]] = ov
        for pr in problems:
            report["needs a hand override"].append("%s: %s" % (h["package"], pr))

    src = "%s %s %s: %d overrides" % (os.path.basename(os.path.dirname(os.path.abspath(a.lcginfo))),
                                      a.flavour, a.platform, len(ovs))
    gen = block(ovs, src)
    if a.write:
        if BEGIN not in text:
            sys.exit("%s has no generated block: add the two marker lines under "
                     "overrides:\n%s\n%s" % (a.defaults, BEGIN, END))
        with open(a.defaults, "w") as fh:
            fh.write(pre + gen + post)
    else:
        print(gen)
    for what, items in report.items():
        if items:
            print("\n# %s (%d):" % (what, len(items)), file=sys.stderr)
            for i in items:
                print("#   " + i, file=sys.stderr)
    return 1 if report["needs a hand override"] else 0


if __name__ == "__main__":
    sys.exit(main())
